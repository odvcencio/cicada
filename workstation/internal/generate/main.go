package main

import (
	"crypto/sha256"
	"fmt"
	"go/format"
	"log"
	"os"
	"os/exec"
	"path/filepath"
	"strings"

	"m31labs.dev/gosx"
	"m31labs.dev/gosx/ir"
	islandprogram "m31labs.dev/gosx/island/program"
	"m31labs.dev/gosx/transpile"
)

func main() {
	if err := generateUI("."); err != nil {
		log.Fatal(err)
	}
	if err := os.MkdirAll("build", 0755); err != nil {
		log.Fatal(err)
	}
	command := exec.Command("go", "build", "-trimpath", "-buildvcs=false", "-ldflags=-s -w", "-o", "build/cicada-meters.wasm", "./engine")
	command.Env = append(os.Environ(), "GOOS=js", "GOARCH=wasm", "CGO_ENABLED=0", "GOWORK=off")
	command.Stderr = os.Stderr
	if err := command.Run(); err != nil {
		log.Fatal(err)
	}
	wasm, err := os.ReadFile("build/cicada-meters.wasm")
	if err != nil {
		log.Fatal(err)
	}
	// The UI shares a single module across its mounts. Importing a host package
	// can retain compiler registries even when the UI never calls them.
	const maxEngineBytes = 16 << 20
	if len(wasm) > maxEngineBytes {
		log.Fatalf("UI engine is %d bytes; exceeds %d-byte budget (check host/compiler imports)", len(wasm), maxEngineBytes)
	}
	log.Printf("UI engine: %d bytes (budget %d)", len(wasm), maxEngineBytes)
	digest := sha256.Sum256(wasm)
	name := fmt.Sprintf("cicada-meters.%x.wasm", digest[:8])
	if err := os.MkdirAll("public/engines", 0755); err != nil {
		log.Fatal(err)
	}
	// Clean only our generated, content-addressed engine assets.
	old, err := filepath.Glob("public/engines/cicada-meters.*.wasm")
	if err != nil {
		log.Fatal(err)
	}
	for _, path := range old {
		if filepath.Base(path) != name && strings.HasPrefix(filepath.Base(path), "cicada-meters.") {
			if err := os.Remove(path); err != nil {
				log.Fatal(err)
			}
		}
	}
	if err := os.WriteFile(filepath.Join("public/engines", name), wasm, 0644); err != nil {
		log.Fatal(err)
	}
}

// Project strict server components separately from VM-only island functions.
// The program table lets request handlers mount any island from any UI file.
func generateUI(root string) error {
	files, err := filepath.Glob(filepath.Join(root, "app/ui/*.gsx"))
	if err != nil {
		return err
	}
	if len(files) == 0 {
		return fmt.Errorf("no UI components found")
	}
	if err := os.MkdirAll(filepath.Join(root, "ui"), 0755); err != nil {
		return err
	}
	var table strings.Builder
	table.WriteString("// Code generated by go generate; DO NOT EDIT.\npackage ui\nimport islandprogram \"m31labs.dev/gosx/island/program\"\nvar IslandPrograms = map[string]*islandprogram.Program{\n")
	for _, path := range files {
		source, err := os.ReadFile(path)
		if err != nil {
			return err
		}
		program, err := gosx.Compile(source)
		if err != nil {
			return fmt.Errorf("%s: %w", path, err)
		}
		// Transpile with a root-relative source name: the strict projection
		// would embed absolute //line paths in the generated file.
		rel, err := filepath.Rel(root, path)
		if err != nil {
			return err
		}
		code, err := transpile.Transpile(source, transpile.Options{SourceFile: filepath.ToSlash(rel)})
		if err != nil {
			return fmt.Errorf("%s: %w", path, err)
		}
		name := strings.TrimSuffix(filepath.Base(path), ".gsx") + "_gsx.go"
		if err := writeGo(filepath.Join(root, "ui", name), "// Code generated by go generate; DO NOT EDIT.\n"+code); err != nil {
			return err
		}
		for index, component := range program.Components {
			if !component.IsIsland {
				continue
			}
			lowered, err := ir.LowerIsland(program, index)
			if err != nil {
				return err
			}
			encoded, err := islandprogram.EncodeJSON(lowered)
			if err != nil {
				return err
			}
			fmt.Fprintf(&table, "%q: decodeIslandProgram(%q),\n", component.Name, encoded)
		}
	}
	table.WriteString("}\nfunc decodeIslandProgram(source string) *islandprogram.Program {\nprogram, err := islandprogram.DecodeJSON([]byte(source)); if err != nil { panic(err) }; return program\n}\n")
	if err := writeGo(filepath.Join(root, "ui/islands.go"), table.String()); err != nil {
		return err
	}
	styles, err := filepath.Glob(filepath.Join(root, "app/ui/*.css"))
	if err != nil {
		return err
	}
	var css []byte
	for _, path := range styles {
		source, err := os.ReadFile(path)
		if err != nil {
			return err
		}
		if len(css) > 0 {
			css = append(css, '\n')
		}
		css = append(css, source...)
	}
	style := fmt.Sprintf("// Code generated by go generate; DO NOT EDIT.\npackage ui\nvar CSS = []byte(%q)\n", css)
	return writeGo(filepath.Join(root, "ui/style_asset.go"), style)
}

func writeGo(path, source string) error {
	formatted, err := format.Source([]byte(source))
	if err != nil {
		return err
	}
	return os.WriteFile(path, formatted, 0644)
}
