'use strict';
const test = require('node:test');
const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const crypto = require('node:crypto');
if (process.argv[2] === '--write-fixture') {
  fs.writeFileSync(process.argv[3], 'cicada 2\ntrack bass acid {}\npattern p { 1 . }\nscene main { bass = p }\nsong { main }\n', {flag:'wx'});
  process.exit(0);
}
test('add a compressor and undo its parameter and creation', {timeout:120000}, async t => {
  const base=process.env.CICADA_STUDIO_URL, score=process.env.CICADA_ADD_INSERT_SCORE;
  assert.equal(new URL(base).hostname,'127.0.0.1'); assert(path.isAbsolute(score));
  const {chromium}=require(process.env.CICADA_PLAYWRIGHT_MODULE || 'playwright');
  const browser=await chromium.launch({headless:true,executablePath:process.env.CICADA_CHROME_PATH,args:['--no-sandbox','--mute-audio']});
  t.after(()=>browser.close(),{timeout:15000});
  const page=await browser.newPage({viewport:{width:1440,height:1000}});
  const source=()=>fs.readFileSync(score,'utf8'); const original=source();
  const waitSource=async predicate=>{const end=Date.now()+30000; while(Date.now()<end){const s=source(); if(predicate(s)) return s; await new Promise(r=>setTimeout(r,50));} assert.fail('score did not update');};
  const waitRevision=async text=>{const hash=crypto.createHash('sha256').update(text).digest('hex'); await page.waitForFunction(x=>document.querySelector('#mixer form input[name=revision]')?.value===x,hash,{timeout:30000});};
  await page.goto(new URL('/studio?tab=mixer',base).href); await page.locator('#studio-shell[data-shell-actions=ready]').waitFor({timeout:30000});
  await page.locator('#mixer').getByRole('link',{name:'Open bass in Device',exact:true}).click();
  const device=page.locator('#device-editor'); await device.locator('.device-groups[data-device-channel="bass"]').waitFor();
  await page.locator('#detail-tab-device[aria-selected="true"]').waitFor();
  const add=device.locator('form[action$="/__actions/add-effect"]');
  await add.locator('select[name=effectkind]').selectOption('comp'); await add.locator('input[name=name]').fill('glue'); await add.getByRole('button',{name:'Add insert'}).click();
  let saved=await waitSource(s=>s.includes('fx glue comp') && /insert\s*=\s*glue/.test(s)); await waitRevision(saved);
  assert.equal(await device.locator('.device-groups').getAttribute('data-device-channel'),'bass');
  await device.locator('#device-effect-glue summary').click();
  const param=device.locator('form[action$="/__actions/mixer"]').filter({has:page.locator('input[name=path][value="glue.threshold"]')});
  await param.locator('[name=value]').fill('-20'); await param.getByRole('button',{name:'Set',exact:true}).click();
  const edited=await waitSource(s=>s!==saved); await waitRevision(edited);
  await page.locator('#undo-form button').click(); await waitSource(s=>s===saved); await waitRevision(saved);
  await page.locator('#undo-form button').click(); await waitSource(s=>s===original); await waitRevision(original);
  await page.locator('#mixer .mixer-add-effect summary').click();
  const returnForm=page.locator('#mixer form[action$="/__actions/add-effect"]');
  await returnForm.locator('select[name=effectkind]').selectOption('reverb');
  await returnForm.locator('input[name=name]').fill('hall');
  await returnForm.getByRole('button',{name:'Add return'}).click();
  const withReturn=await waitSource(s=>s.includes('fx hall reverb')); await waitRevision(withReturn);
  await page.locator('#mixer').getByRole('link',{name:'Open bass in Device',exact:true}).click();
  const sendForm=device.locator('form[action$="/__actions/mixer"]').filter({has:page.locator('select[name=path]')});
  await sendForm.locator('select[name=path]').selectOption('bass.send.hall');
  await sendForm.getByRole('button',{name:'Add send'}).click();
  const withSend=await waitSource(s=>/send\s+hall\s*=/.test(s)); await waitRevision(withSend);
  assert.match(withSend, /track\s+bass\s+acid\s*\{[^}]*\bsend\s+hall\s*=\s*-12dB\b/s);
  await page.locator('#undo-form button').click(); await waitSource(s=>s===withReturn); await waitRevision(withReturn);
  await page.locator('#undo-form button').click(); await waitSource(s=>s===original); await waitRevision(original);
});
