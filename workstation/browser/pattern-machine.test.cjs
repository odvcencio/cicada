'use strict';
const test=require('node:test'), assert=require('node:assert/strict'), fs=require('node:fs'), path=require('node:path');
if (process.argv[2]==='--write-fixture') {
 fs.writeFileSync(process.argv[3], 'cicada 2\ntitle "Pattern Machine proof"\ntempo 172\nkey f# minor\ntrack keys tine_ep { level = -12dB }\ntrack beat drums { level = -12dB }\npattern original notes { c4 . e4 . }\nscene main { keys = original beat = off }\nsong { main*4 }\n', {flag:'wx'});
} else {
test('generate, vary, audition and keep editable machine patterns', {timeout:150000}, async t=>{
 const base=process.env.CICADA_STUDIO_URL, score=process.env.CICADA_MACHINE_SCORE, proof=process.env.CICADA_MACHINE_PROOF;
 const {chromium}=require(process.env.CICADA_PLAYWRIGHT_MODULE||'playwright');
 const browser=await chromium.launch({headless:true,executablePath:process.env.CICADA_CHROME_PATH,args:['--no-sandbox','--mute-audio']});t.after(()=>browser.close());
 const context=await browser.newContext({viewport:{width:1440,height:1000},reducedMotion:'reduce'}), page=await context.newPage(), errors=[];
 page.on('pageerror',e=>errors.push(e.message));
 const before=fs.readFileSync(score,'utf8');
 await page.goto(new URL('/studio?dock=clip&region=detail&pattern=original&track=keys',base).href);
 await page.locator('#studio-shell[data-shell-actions=ready]').waitFor({timeout:30000});
 await page.locator('#detail-panel-clip [data-machine-open]').first().click();
 await page.locator('[data-machine-preview]').waitFor();
 assert.equal(fs.readFileSync(score,'utf8'),before,'preview wrote the score');
 assert.equal(await page.locator('.machine-bar').count(),4);
 await page.locator('#studio-detail').screenshot({path:path.join(proof,'desktop.png')});
 await page.setViewportSize({width:390,height:844});
 assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),true,'phone overflow');
 await page.locator('#studio-detail').screenshot({path:path.join(proof,'phone.png')});
 await page.setViewportSize({width:1440,height:1000});
 const first=await page.locator('[data-machine-preview]').innerText();
 await page.locator('.machine-controls [name=density]').evaluate(el=>{el.value='72';el.dispatchEvent(new Event('input',{bubbles:true}));});
 await page.getByRole('button',{name:'New variation'}).click();
 await page.waitForFunction(old=>document.querySelector('[data-machine-preview]')?.innerText!==old,first,{timeout:30000});
 assert.equal(await page.locator('.machine-controls [name=density]').inputValue(),'72','variation discarded the current density control');
 assert.equal(fs.readFileSync(score,'utf8'),before,'vary wrote the score');
 const loop=page.locator('#cicada-pattern-preview [data-sound-preview]');
 await loop.waitFor(); await page.waitForFunction(()=>!document.querySelector('#cicada-pattern-preview [data-sound-preview]')?.disabled,{timeout:30000});
 await loop.click(); await page.waitForFunction(()=>document.querySelector('#cicada-pattern-preview [data-sound-preview]')?.textContent==='Stop',null,{timeout:30000});
 assert.equal(fs.readFileSync(score,'utf8'),before,'audition wrote the score');
 await loop.click();
 const keep=page.locator('.machine-keep');await keep.locator('[name=newName]').fill('machine-idea');await keep.getByRole('button',{name:'Keep pattern'}).click();
 await page.waitForFunction(()=>document.querySelector('[data-pattern-id="machine-idea"]'),null,{timeout:30000});
 let changed=fs.readFileSync(score,'utf8');assert.match(changed,/pattern machine-idea notes steps=64/);assert.match(changed,/scene main \{ keys = original beat = off \}/);
 await page.locator('#undo-form button').click();
 await page.waitForFunction(()=>!document.querySelector('[data-pattern-id="machine-idea"]'),null,{timeout:30000});
 assert.equal(fs.readFileSync(score,'utf8'),before,'one undo did not restore the score');
 await page.goto(new URL('/studio?tab=session&dock=device',base).href);
 await page.locator('#studio-shell[data-shell-actions=ready]').waitFor({timeout:30000});
 const browserGenerate=page.locator('#browser-generate');
 if (!await browserGenerate.evaluate(node=>node.open)) await browserGenerate.locator('summary').first().click();
 await browserGenerate.locator('[data-machine-open]').click();
 await page.locator('[data-machine-preview]').waitFor();
 assert.match(await page.url(),/dock=clip/,'Generate did not open the Clip workspace');
 await page.locator('.machine-controls select[name=track]').selectOption('beat');
 await page.locator('.machine-controls button').click();
 await page.getByRole('heading',{name:'Breakbeat drums'}).waitFor();
 assert.equal(await page.locator('.machine-bar').count(),4);
 const drumLoop=page.locator('#cicada-pattern-preview [data-sound-preview]');
 await page.waitForFunction(()=>!document.querySelector('#cicada-pattern-preview [data-sound-preview]')?.disabled,{timeout:30000});
 await drumLoop.click();
 await page.waitForFunction(()=>document.querySelector('#cicada-pattern-preview [data-sound-preview]')?.textContent==='Stop',null,{timeout:30000});
 assert.equal(fs.readFileSync(score,'utf8'),before,'drum audition wrote the score');
 await drumLoop.click();
 await page.locator('.machine-keep [name=newName]').fill('machine-beat');
 await page.locator('.machine-keep').getByRole('button',{name:'Keep pattern'}).click();
 await page.waitForFunction(()=>document.querySelector('[data-pattern-id="machine-beat"]'),null,{timeout:30000});
 changed=fs.readFileSync(score,'utf8');assert.match(changed,/pattern machine-beat drums steps=64/);assert.match(changed,/oh:/);assert.match(changed,/rs:/);
 await page.locator('#undo-form button').click();
 await page.waitForFunction(()=>!document.querySelector('[data-pattern-id="machine-beat"]'),null,{timeout:30000});
 assert.equal(fs.readFileSync(score,'utf8'),before,'drum undo did not restore the score');
 assert.deepEqual(errors,[]);
 fs.writeFileSync(path.join(proof,'report.json'),JSON.stringify({checks:['visual preview without writes','variation','melodic and drum audition without writes','keep new note and drum patterns','one undo each','Generate navigation'],errors},null,2));
});
}
