/* Fresh private eight-bar/three-take Studio fixture, native --audio null only.
 * CICADA_PRODUCER_URL/SCORE/PROOF_DIR plus the usual Playwright/Chrome envs.
 * All mutations use visible controls. Source edits are confined to /tmp. */
'use strict';
const test = require('node:test');
const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const crypto = require('node:crypto');

async function until(fn, message) {
  const end = Date.now() + 20000;
  while (Date.now() < end) {
    if (await fn()) return;
    await new Promise(resolve => setTimeout(resolve, 50));
  }
  assert.fail(message);
}

test('Producer workflow edits vocal timing, joins, effect chains and drawn automation with retained raw takes', { timeout: 180000 }, async t => {
  const base = process.env.CICADA_PRODUCER_URL;
  const score = process.env.CICADA_PRODUCER_SCORE;
  const proof = process.env.CICADA_PRODUCER_PROOF_DIR;
  assert.ok(base && new URL(base).hostname === '127.0.0.1');
  assert.ok(score && path.isAbsolute(score) && score.startsWith('/tmp/'), 'only a disposable /tmp score may be edited');
  const initialSource = fs.readFileSync(score, 'utf8');
  assert.ok(initialSource.includes('// cicada-vocal-test: disposable fixture'));
  const { chromium } = require(process.env.CICADA_PLAYWRIGHT_MODULE || 'playwright');
  const browser = await chromium.launch({ headless: true, executablePath: process.env.CICADA_CHROME_PATH, args: ['--no-sandbox'] });
  const storage = process.env.CICADA_PRODUCER_STORAGE || '/tmp/cicada-pro2-browser-session.json';
  assert.ok(path.isAbsolute(storage) && storage.startsWith('/tmp/'));
  const desktop = await browser.newContext({ viewport: { width: 1440, height: 1100 }, reducedMotion: 'reduce', ...(fs.existsSync(storage) ? { storageState: storage } : {}) });
  t.after(async () => { await desktop.storageState({ path: storage }); await browser.close(); });
  const page = await desktop.newPage();
  page.setDefaultTimeout(20000);
  const errors = [], checks = [];
  page.on('pageerror', error => errors.push(error.message));
  const actionResponse = response => {
    if (response.url().includes('/__actions/') && response.status() >= 400) errors.push(`editor action failed ${response.status()}: ${new URL(response.url()).pathname}`);
  };
  page.on('response', actionResponse);
  const json = async route => {
    const response = await page.request.get(base + route);
    assert.equal(response.status(), 200, route);
    return response.json();
  };
  const state = () => json('/api/state');
  const takes = () => json('/api/takes');
  const transport = () => json('/api/transport');
  const ready = async (target, vocals = true) => {
    await target.locator('#cicada-workspace[data-workspace-reactive=ready]').waitFor();
    await target.locator('#cicada-workspace[aria-busy=true]').waitFor({ state: 'hidden' });
    if (vocals) await target.locator('#cicada-vocal-lanes[data-vocal-lanes-ready=true]').waitFor();
    assert.deepEqual(errors, [], 'browser/action errors');
  };
  const navigate = async (target, panel) => {
    await target.getByRole('link', { name: panel, exact: true }).click();
    if (panel === 'Mixer') await target.locator('#mixer').waitFor();
    await ready(target, panel === 'Session');
  };
  const rawHashes = raw => raw.map(take => {
    const root = path.dirname(score), absolute = path.resolve(root, take.asset.path);
    assert.ok(absolute.startsWith(root + path.sep));
    const hash = crypto.createHash('sha256').update(fs.readFileSync(absolute)).digest('hex');
    assert.equal(hash, take.asset.sha256);
    return { id: take.id, hash, frames: take.frames };
  }).sort((a, b) => a.id.localeCompare(b.id));
  const comp = async () => (await takes()).comps.find(value => value.track === 'vox');
  const editValues = async target => Object.fromEntries(await Promise.all([
    ['offsetMS', 'Advance phrase (ms)'], ['fadeMS', 'Edge fade (ms)'], ['crossfadeMS', 'Join crossfade (ms)'], ['gainDB', 'Phrase gain (dB)'],
  ].map(async ([name, label]) => [name, Number(await target.getByLabel(label, { exact: true }).inputValue())])));
  const range = async target => [await target.getByLabel('Range start', { exact: true }).inputValue(), await target.getByLabel('Range end', { exact: true }).inputValue()];
  const chosen = (target, id) => target.locator(`.vocal-comp-region[data-vocal-pick="${id}"][data-vocal-start="7680"][data-vocal-end="11520"]`);
  const openTiming = async target => {
    if (!(await target.getByLabel('Advance phrase (ms)', { exact: true }).isVisible())) await target.getByText('Timing and transitions', { exact: true }).click();
  };
  const saveScreenshot = async (target, selector, name) => {
    if (proof) { fs.mkdirSync(proof, { recursive: true }); await target.locator(selector).screenshot({ path: path.join(proof, name) }); }
  };

  await page.goto(base + '/?panel=session', { waitUntil: 'domcontentloaded' });
  await ready(page);
  assert.equal((await state()).source, initialSource);
  const raw = (await takes()).takes, beforeHashes = rawHashes(raw);
  assert.equal(raw.length, 3);
  const full = raw.filter(value => value.timeline.startTick === 0);
  assert.equal(full.length, 2);
  const first = full[0].id, second = full[1].id;
  const passSelect = page.getByLabel('Passes', { exact: true });
  assert.deepEqual(await passSelect.locator('option').evaluateAll(options => options.map(option => option.value)), ['1','2','3','4','5','6','7','8']);
  await passSelect.selectOption('3');
  assert.equal(await passSelect.inputValue(), '3');
  await passSelect.selectOption('1');
  assert.equal((await json('/api/audio/config')).options.inputEnabled, false);
  checks.push('finite recording pass choices1–8 are available without opening the microphone');

  await page.locator(`[data-vocal-take="${first}"] [data-vocal-pick]`).click();
  await page.getByRole('button', { name: 'Use whole take', exact: true }).click();
  await ready(page);
  const canonical = (await state()).source;
  await page.locator(`[data-vocal-take="${second}"] [data-vocal-pick]`).click();
  await page.locator('.vocal-exact > summary').click();
  await page.getByLabel('Range start', { exact: true }).fill('@3.1.1');
  await page.getByLabel('Range end', { exact: true }).fill('@4.1.1');
  await page.getByLabel('Phrase gain (dB)', { exact: true }).focus();
  await openTiming(page);
  await page.getByLabel('Advance phrase (ms)', { exact: true }).fill('5');
  await page.getByLabel('Edge fade (ms)', { exact: true }).fill('8');
  await page.getByLabel('Join crossfade (ms)', { exact: true }).fill('12');
  await page.getByLabel('Phrase gain (dB)', { exact: true }).fill('-3');
  await page.getByLabel('Hear with', { exact: true }).selectOption('solo');
  await page.getByRole('button', { name: 'Earlier 5 ms', exact: true }).click();
  assert.equal(Number(await page.getByLabel('Advance phrase (ms)', { exact: true }).inputValue()), 10);
  await page.getByRole('button', { name: 'Later 5 ms', exact: true }).click();
  assert.deepEqual(await editValues(page), { offsetMS: 5, fadeMS: 8, crossfadeMS: 12, gainDB: -3 });
  assert.deepEqual(await range(page), ['@3.1.1', '@4.1.1']);
  await page.getByRole('button', { name: 'Hear selection', exact: true }).click();
  await ready(page);
  await until(async () => (await transport()).listening?.mode === 'solo', 'phrase preview did not start in vocal-only mode');
  assert.equal((await state()).source, canonical);
  await page.getByRole('button', { name: 'Stop audition', exact: true }).click();
  await ready(page);
  assert.deepEqual(await editValues(page), { offsetMS: 5, fadeMS: 8, crossfadeMS: 12, gainDB: -3 });
  checks.push('timing nudges preserve the selected interval; gain/advance/fades preview without source edits');

  await page.getByRole('button', { name: 'Use selection', exact: true }).click();
  await ready(page);
  const edited = (await state()).source;
  const saved = (await comp()).segments.find(value => value.take === second);
  assert.deepEqual([saved.startTick, saved.endTick, saved.offsetMS, saved.fadeMS, saved.crossfadeMS, saved.gainDB], [7680, 11520, 5, 8, 12, -3]);
  assert.equal((await comp()).segments.length, 3);
  await page.getByRole('button', { name: 'Undo', exact: true }).click();
  await ready(page);
  assert.equal((await state()).source, canonical);
  await page.getByRole('button', { name: 'Redo', exact: true }).click();
  await ready(page);
  assert.equal((await state()).source, edited);
  await chosen(page, second).click();
  await openTiming(page);
  assert.deepEqual(await editValues(page), { offsetMS: 5, fadeMS: 8, crossfadeMS: 12, gainDB: -3 });
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true, 'producer controls overflow desktop');
  await saveScreenshot(page, '#vocals', 'producer-vocal-timing-1440.png');
  checks.push('phrase timing and transitions commit with independent neighbor mappings and survive Undo/Redo');

  await page.getByRole('link', { name: 'Choose microphone and output', exact: true }).click();
  await ready(page, false);
  await page.getByText('Recording timing', { exact: true }).click();
  await page.getByLabel('Recording timing correction (ms)', { exact: true }).fill('23.5');
  await page.getByRole('button', { name: 'Apply and return to recording', exact: true }).click();
  await ready(page);
  const audio = await json('/api/audio/config');
  assert.equal(audio.options.recordingOffsetMS, 23.5);
  assert.equal(audio.options.inputEnabled, false);
  assert.equal((await json('/api/capture')).activeCapture, '');
  assert.equal((await state()).source, edited);
  checks.push('recording timing correction applies through Audio and returns to Session with microphone off');

  await navigate(page, 'Mixer');
  const addChain = page.getByRole('button', { name: 'Add vocal chain', exact: true });
  assert.ok(await addChain.count() >= 1);
  await addChain.first().click();
  await ready(page, false);
  const chain = page.getByLabel('vox insert chain', { exact: true });
  const names = async () => chain.locator('ol li a').allTextContents();
  const originalNames = await names();
  assert.equal(originalNames.length, 3);
  const withChain = (await state()).source;
  await page.getByRole('button', { name: 'Add vocal chain', exact: true }).first().click();
  await ready(page, false);
  assert.deepEqual(await names(), originalNames);
  assert.equal((await state()).source, withChain, 'preset duplicated or changed an existing chain');
  await page.getByRole('button', { name: `Move ${originalNames[1]} earlier`, exact: true }).click();
  await ready(page, false);
  assert.deepEqual(await names(), [originalNames[1], originalNames[0], originalNames[2]]);
  await page.getByRole('button', { name: `Move ${originalNames[1]} later`, exact: true }).click();
  await ready(page, false);
  assert.deepEqual(await names(), originalNames);
  await page.getByRole('button', { name: `Remove ${originalNames[2]}`, exact: true }).click();
  await ready(page, false);
  assert.deepEqual(await names(), originalNames.slice(0, 2));
  await page.getByRole('button', { name: 'Undo', exact: true }).click();
  await ready(page, false);
  assert.deepEqual(await names(), originalNames);
  await saveScreenshot(page, '[aria-label="vox insert chain"]', 'producer-vocal-chain-1440.png');
  checks.push('vocal chain creation is idempotent; insert order and removal are explicit and undoable');

  await navigate(page, 'Session');
  await chosen(page, second).click();
  await openTiming(page);
  await page.getByLabel('Phrase gain (dB)', { exact: true }).fill('-4');
  await page.getByLabel('Hear with', { exact: true }).selectOption('solo');
  const beforeChainedPhrase = (await state()).source;
  await page.getByRole('button', { name: 'Hear selection', exact: true }).click();
  await ready(page);
  await until(async () => (await transport()).listening?.mode === 'solo', 'phrase preview with vocal effects did not start');
  assert.equal((await state()).source, beforeChainedPhrase, 'audition with vocal effects changed the score');
  await page.getByRole('button', { name: 'Stop audition', exact: true }).click();
  await ready(page);
  await page.getByRole('button', { name: 'Use selection', exact: true }).click();
  await ready(page);
  const chainedPhrase = (await state()).source;
  assert.notEqual(chainedPhrase, beforeChainedPhrase);
  assert.equal((await comp()).segments.find(value => value.take === second).gainDB, -4);
  for (const name of originalNames) assert.ok(chainedPhrase.includes(`fx ${name.trim()} `), `comp removed vocal effect ${name}`);
  await page.getByRole('button', { name: 'Undo', exact: true }).click();
  await ready(page);
  assert.equal((await state()).source, beforeChainedPhrase);
  await chosen(page, second).click();
  await openTiming(page);
  assert.deepEqual(await editValues(page), { offsetMS: 5, fadeMS: 8, crossfadeMS: 12, gainDB: -3 });
  checks.push('a phrase can be auditioned and recomped after adding its vocal effects; effects and source Undo remain intact');

  await page.getByLabel('Automation parameter', { exact: true }).selectOption('vox.level');
  await page.getByRole('button', { name: 'Show curve', exact: true }).click();
  await ready(page);
  const curveReady = async target => target.locator('#cicada-automation-curve[data-automation-ready=true]').waitFor();
  const points = async target => JSON.parse(await target.locator('[data-automation-curve-props]').getAttribute('data-automation-curve-props')).Points;
  await curveReady(page);
  await until(async () => await page.locator('[data-waveform-state=ready]').count() === 3, 'Session waveforms did not settle before curve interaction');
  const graph = page.locator('svg[data-automation-curve]');
  await graph.scrollIntoViewIfNeeded();
  let box = await graph.boundingBox();
  const beforeCurve = (await state()).source;
  await graph.dblclick({ position: { x: box.width * .2, y: box.height * .45 } });
  await until(async () => await page.locator('[data-curve-point]').count() === 1, 'SVG-relative double-click did not create a draft point');
  assert.equal(await page.locator('[data-curve-point]').count(), 1);
  assert.equal((await state()).source, beforeCurve);
  await page.getByLabel('Point value', { exact: true }).fill('-18dB');
  const draftPosition = await page.getByLabel('Point position', { exact: true }).inputValue();
  await page.getByRole('button', { name: 'Show curve', exact: true }).click();
  await ready(page);
  await curveReady(page);
  assert.equal(await page.locator('[data-curve-point]').count(), 1, 'showing the same curve discarded a new draft');
  assert.equal(await page.getByLabel('Point position', { exact: true }).inputValue(), draftPosition);
  assert.equal(await page.getByLabel('Point value', { exact: true }).inputValue(), '-18dB');
  assert.equal((await state()).source, beforeCurve);
  assert.equal(await page.getByRole('button', { name: 'Remove selected point', exact: true }).isDisabled(), true, 'unsaved new point offered canonical deletion');
  await page.getByRole('button', { name: 'Save point', exact: true }).click();
  await ready(page);
  await curveReady(page);
  await until(async () => (await points(page)).length === 1, 'saved curve point did not reach the canonical UI');
  let savedPoints = await points(page);
  assert.equal(savedPoints.length, 1);
  const oldTick = savedPoints[0].tick;
  await page.locator('[data-curve-point]').first().focus();
  for (let move = 0; move < 3; move++) await page.keyboard.press('ArrowRight');
  await page.getByRole('button', { name: 'Save point', exact: true }).click();
  await ready(page);
  await until(async () => { const values = await points(page); return values.length === 1 && values[0].tick === oldTick + 720; }, 'moved point did not replace its canonical original position');
  savedPoints = await points(page);
  assert.equal(savedPoints.length, 1, 'repeated keyboard moves duplicated the old point');
  assert.equal(savedPoints[0].tick, oldTick + 720);
  await graph.scrollIntoViewIfNeeded();
  box = await graph.boundingBox();
  await graph.dblclick({ position: { x: box.width * .72, y: box.height * .3 } });
  await until(async () => await page.locator('[data-curve-point]').count() === 2, 'second curve draft did not appear');
  await page.getByLabel('Point value', { exact: true }).fill('-9dB');
  await page.getByLabel('Transition', { exact: true }).selectOption('curve');
  await page.getByLabel('Curve tension', { exact: true }).fill('2');
  await page.getByRole('button', { name: 'Save point', exact: true }).click();
  await ready(page);
  await until(async () => { const values = await points(page); return values.length === 2 && values[1].shape === 'curve' && values[1].curve === 2; }, 'second saved curve point did not update');
  savedPoints = await points(page);
  assert.equal(savedPoints.length, 2);
  assert.equal(savedPoints[1].shape, 'curve');
  assert.equal(savedPoints[1].curve, 2);
  const curveSource = (await state()).source;
  await page.locator('[data-curve-point]').nth(1).click();
  await page.getByRole('button', { name: 'Remove selected point', exact: true }).click();
  await ready(page);
  await until(async () => (await points(page)).length === 1, 'selected point did not delete');
  assert.equal((await points(page)).length, 1);
  await page.getByRole('button', { name: 'Undo', exact: true }).click();
  await ready(page);
  await until(async () => (await state()).source === curveSource && (await points(page)).length === 2, 'Undo did not restore the saved curve');
  assert.equal((await state()).source, curveSource);
  assert.equal((await points(page)).length, 2);
  const priorPoints = await points(page);
  await page.getByRole('button', { name: 'New point', exact: true }).click();
  assert.equal(await page.locator('[data-curve-point]').count(), 3);
  assert.equal(await page.getByLabel('Point position', { exact: true }).inputValue(), '@1.1.1', 'New point did not choose the first unused sixteenth');
  assert.equal((await state()).source, curveSource, 'New point committed its draft');
  await page.getByLabel('Point value', { exact: true }).fill('-24dB');
  await page.getByRole('button', { name: 'Save point', exact: true }).click();
  await ready(page);
  await until(async () => (await points(page)).length === 3, 'New point did not save');
  await page.locator('[data-curve-point]').first().click();
  await page.getByRole('button', { name: 'Remove selected point', exact: true }).click();
  await ready(page);
  await until(async () => (await points(page)).length === 2, 'new button-created point did not delete');
  assert.deepEqual(await points(page), priorPoints);
  await saveScreenshot(page, '#automation-editor', 'producer-automation-1440.png');
  checks.push('drawn and button-created points stay drafts until saved; repeated keyboard moves replace one point; curve shape/deletion support Undo');

  const mobile = await browser.newContext({ viewport: { width: 390, height: 844 }, isMobile: true, hasTouch: true, reducedMotion: 'reduce', storageState: await desktop.storageState() });
  const phone = await mobile.newPage();
  phone.setDefaultTimeout(20000);
  phone.on('pageerror', error => errors.push(error.message));
  phone.on('response', actionResponse);
  await phone.goto(base + '/?panel=session&curvePath=vox.level', { waitUntil: 'domcontentloaded' });
  await ready(phone);
  await curveReady(phone);
  await chosen(phone, second).click();
  await openTiming(phone);
  assert.deepEqual(await editValues(phone), { offsetMS: 5, fadeMS: 8, crossfadeMS: 12, gainDB: -3 });
  await saveScreenshot(phone, '#vocals', 'producer-vocal-timing-390.png');
  const touchPoint = phone.locator('[data-curve-point]').first();
  await touchPoint.scrollIntoViewIfNeeded();
  const circle = await touchPoint.boundingBox();
  const positionBefore = await phone.getByLabel('Point position', { exact: true }).inputValue();
  const beforeTouchSource = (await state()).source;
  const cdp = await mobile.newCDPSession(phone);
  const touch = (type, dx, dy) => cdp.send('Input.dispatchTouchEvent', { type, touchPoints: type === 'touchEnd' ? [] : [{ x: circle.x + circle.width / 2 + dx, y: circle.y + circle.height / 2 + dy }] });
  await touch('touchStart', 0, 0);
  for (let step = 1; step <= 8; step++) await touch('touchMove', step * 3, -step * 2);
  await touch('touchEnd', 0, 0);
  await until(async () => await phone.getByLabel('Point position', { exact: true }).inputValue() !== positionBefore, 'real touch did not move the automation point');
  assert.equal((await state()).source, beforeTouchSource);
  await phone.getByRole('button', { name: 'Save point', exact: true }).click();
  await ready(phone);
  await until(async () => (await state()).source !== beforeTouchSource, 'touch-moved point did not commit');
  assert.equal((await points(phone)).length, 2);
  assert.equal(await phone.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true, 'producer controls overflow the phone screen');
  await saveScreenshot(phone, '#automation-editor', 'producer-automation-390.png');
  checks.push('phone phrase controls recall saved edits; real touch moves and saves a curve point without duplicating it or overflowing');
  const afterHashes = rawHashes((await takes()).takes);
  assert.deepEqual(afterHashes, beforeHashes);
  assert.equal((await json('/api/capture')).activeCapture, '');
  assert.equal((await json('/api/audio/config')).options.inputEnabled, false);
  assert.deepEqual(errors, []);
  if (proof) fs.writeFileSync(path.join(proof, 'checks.json'), JSON.stringify({ checks, errors, beforeHashes, afterHashes, microphoneActivated: false, silentOutput: true, desktop: [1440,1100], phone: [390,844] }, null, 2));
  await mobile.close();
  console.log(checks.join('\n'));
});
