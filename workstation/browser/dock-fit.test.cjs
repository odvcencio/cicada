'use strict';
const test=require('node:test');
const assert=require('node:assert/strict');
const fs=require('node:fs');
const path=require('node:path');

test('dock resizing fits the window and preserves musical work',{timeout:120000},async t=>{
 const {chromium}=require(process.env.CICADA_PLAYWRIGHT_MODULE||'playwright');
 const browser=await chromium.launch({headless:true,executablePath:process.env.CICADA_CHROME_PATH});
 t.after(()=>browser.close());
 const page=await browser.newPage({viewport:{width:1440,height:1000}});
 const errors=[];page.on('pageerror',error=>errors.push(error.message));
 const proof=process.env.CICADA_DOCK_PROOF_DIR;assert.ok(path.isAbsolute(proof));fs.mkdirSync(proof,{recursive:true});
 const startup=new URL(process.env.CICADA_STUDIO_URL);assert.equal(startup.hostname,'127.0.0.1');
 await page.goto(startup.href);await page.goto(new URL('/studio?tab=session',startup).href);
 const ready=()=>page.locator('#studio-shell[data-shell-actions=ready][data-shell-layout=ready]').waitFor();await ready();
 const handle=()=>page.getByRole('separator',{name:'Resize Detail dock',exact:true});
 const geometry=()=>page.evaluate(()=>{
  const rect=id=>{const b=document.querySelector(id).getBoundingClientRect();return {height:b.height,bottom:b.bottom};};
  const h=document.querySelector('[aria-label="Resize Detail dock"]');
  return {center:rect('#studio-center'),dock:rect('#studio-detail'),top:rect('.gsx-dock__top'),height:innerHeight,value:Number(h.getAttribute('aria-valuenow')),minimum:Number(h.getAttribute('aria-valuemin')),maximum:Number(h.getAttribute('aria-valuemax')),stored:JSON.parse(localStorage.getItem('studio:layout:dockHeight'))};
 });
 const until=async(check,label)=>{const end=Date.now()+10000;while(Date.now()<end){if(await check())return;await new Promise(resolve=>setTimeout(resolve,30));}assert.fail(label);};
 const fits=async()=>{const g=await geometry();assert.ok(g.center.height>=199,JSON.stringify(g));assert.ok(g.dock.bottom<=g.height+1,JSON.stringify(g));assert.ok(Math.abs(g.dock.height-g.value)<1,JSON.stringify(g));assert.ok(g.value<=g.maximum,JSON.stringify(g));assert.equal(g.value,g.stored);return g;};
 await handle().focus();await page.keyboard.press('End');
 await until(async()=>Math.abs((await geometry()).dock.height-640)<1,'tall window permits 640 pixels');
 const snapshots=[{label:'tall',...await fits()}];
 await page.setViewportSize({width:1280,height:720});
 await until(async()=>{const g=await geometry();return g.value===g.maximum&&g.maximum<640&&Math.abs(g.value-g.dock.height)<1;},'short window synchronizes size and bounds');
 snapshots.push({label:'short',...await fits()});await page.screenshot({path:path.join(proof,'desktop-fit.png')});
 const before=await geometry();await handle().focus();await page.keyboard.press('ArrowDown');
 await until(async()=>Math.abs((await geometry()).dock.height-(before.dock.height-8))<1,'first keyboard move starts at the visible size');
 const box=await handle().boundingBox();await page.mouse.move(box.x+box.width/2,box.y+4);await page.mouse.down();await page.mouse.move(box.x+box.width/2,box.y+20,{steps:4});await page.mouse.up();
 await until(async()=>Math.abs((await geometry()).dock.height-(before.dock.height-24))<1,'first pointer drag follows sixteen pixels');await fits();
 await page.reload();await ready();snapshots.push({label:'reopened short',...await fits()});
 const editor=page.locator('#score textarea');const initial=await page.evaluate(async()=>{const r=await fetch('/api/state',{cache:'no-store'});return r.json();});
 const draft=await editor.inputValue()+'\n// unsaved window sizing proof\n';await editor.fill(draft);
 await page.locator('#detail-tab-device').click();await handle().focus();await page.keyboard.press('End');await fits();
 assert.equal(await editor.inputValue(),draft);
 const after=await page.evaluate(async()=>{const r=await fetch('/api/state',{cache:'no-store'});return r.json();});assert.equal(after.source,initial.source);assert.equal(after.revision,initial.revision);
 await page.setViewportSize({width:1024,height:480});
 await until(async()=>{const g=await geometry();return g.dock.bottom<=g.height+1&&Math.abs(g.value-g.dock.height)<1;},'compact window fits');snapshots.push({label:'compact',...await fits()});
 await page.setViewportSize({width:390,height:900});
 await page.locator('.shell-phone-nav a').filter({hasText:'Detail'}).click();
 await page.screenshot({path:path.join(proof,'phone-detail.png')});
 assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),true);
 await page.setViewportSize({width:1280,height:720});await page.locator('#detail-tab-clip').click();await ready();await fits();
 assert.equal(await editor.inputValue(),draft);assert.deepEqual(errors,[]);
 fs.writeFileSync(path.join(proof,'fit-report.json'),JSON.stringify({snapshots,errors,checks:['restore across window sizes','first keyboard and pointer movement','bounds and ARIA','reload persistence','local navigation','unsaved score preserved','compact window','phone roundtrip']},null,2)+'\n');
});
