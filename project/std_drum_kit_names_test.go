// oldDrumMachinesPin is the std/drum-machines hash from before the kits were
// renamed; existing projects have it in their cicada.sum.
const oldDrumMachinesPin = "86c5317c6fca18853fc495e34acd8aabee6ae6ad91f7be3acf69829c3b3dad16"

func drumKitProject(t *testing.T, kit, sum string) string {
	t.Helper()
	t.Setenv("CICADA_LIBRARY", t.TempDir())
	root := t.TempDir()
	libraryWrite(t, root, "cicada.mod", "project kit-names\ncicada 2\nentry \"main.cicada\"\n")
	libraryWrite(t, root, "main.cicada", "cicada 2\nimport \"std/drum-machines\"\ntrack k drum-machines."+kit+" {}\npattern p drums steps=4 { bd: x... }\nscene main { k = p }\nsong { main }\n")
	if sum != "" {
		libraryWrite(t, root, "cicada.sum", "# cicada.sum: generated by cicada lib update\nstd/drum-machines std sha256:"+sum+"\n")
	}
	return root
}

func TestDrumKitNamesLoad(t *testing.T) {
	for _, kit := range []string{"boom-kit", "punch-kit", "eight-oh-eight", "nine-oh-nine"} {
		root := drumKitProject(t, kit, "")
		pinLibraryFixture(t, root)
		score, ds, err := LoadScore(filepath.Join(root, "main.cicada"), nil)
		if err != nil || score == nil || len(ds) != 0 {
			t.Fatalf("%s: %v %+v", kit, err, ds)
		}
	}
}

// A project pinned before the rename keeps loading, with the old kit names
// and with the new ones, until the owner re-pins.
func TestOldDrumMachinesPinStillLoads(t *testing.T) {
	for _, kit := range []string{"eight-oh-eight", "nine-oh-nine", "boom-kit", "punch-kit"} {
		root := drumKitProject(t, kit, oldDrumMachinesPin)
		score, ds, err := LoadScore(filepath.Join(root, "main.cicada"), nil)
		if err != nil || score == nil || len(ds) != 0 {
			t.Fatalf("old pin with %s: %v %+v", kit, err, ds)
		}
	}
}

func TestOtherDrumMachinesPinsStillFail(t *testing.T) {
	root := drumKitProject(t, "boom-kit", strings.Repeat("0", 64))
	d := requireLibraryDiagnostic(t, root, "CICADA-LIB-HASH")
	if d.Code != "CICADA-LIB-HASH" {
		t.Fatal(d)
	}
}

func TestDrumMachinesUpdateMovesOldPin(t *testing.T) {
	root := drumKitProject(t, "boom-kit", oldDrumMachinesPin)
	sources, err := ReadSources(filepath.Join(root, "main.cicada"), nil)
	if err != nil {
		t.Fatal(err)
	}
	data, changes, err := sources.UpdateLibraries("std/drum-machines")
	if err != nil || len(changes) != 1 || strings.Contains(string(data), oldDrumMachinesPin) {
		t.Fatalf("update: %v %v\n%s", changes, err, data)
	}
}

func pinCodes(t *testing.T, imp, track, sum string, overrides map[string][]byte) []string {
	t.Helper()
	t.Setenv("CICADA_LIBRARY", t.TempDir())
	root := t.TempDir()
	libraryWrite(t, root, "cicada.mod", "project kit-names\ncicada 2\nentry \"main.cicada\"\n")
	libraryWrite(t, root, "main.cicada", "cicada 2\nimport \""+imp+"\"\ntrack k "+track+" {}\npattern p drums steps=4 { bd: x... }\nscene main { k = p }\nsong { main }\n")
	libraryWrite(t, root, "cicada.sum", "# cicada.sum: generated by cicada lib update\n"+sum+"\n")
	_, ds, err := LoadScore(filepath.Join(root, "main.cicada"), overrides)
	var codes []string
	if err != nil {
		var d *SourceError
		if !errors.As(err, &d) {
			t.Fatal(err)
		}
		ds = append(ds, d.Diagnostic)
	}
	for _, d := range ds {
		codes = append(codes, d.Code)
	}
	return codes
}

func hasCode(codes []string, code string) bool {
	for _, c := range codes {
		if c == code {
			return true
		}
	}
	return false
}

// The old pin is a pin to one successor library, not to any later one.
func TestOldDrumMachinesPinRejectsChangedLibrary(t *testing.T) {
	t.Setenv("CICADA_LIBRARY", t.TempDir())
	lib, err := InspectLibrary(t.TempDir(), "std/drum-machines")
	if err != nil {
		t.Fatal(err)
	}
	file := lib.Files[0]
	changed := strings.Replace(string(file.Source), "env(gate, 360ms)", "env(gate, 380ms)", 1)
	if changed == string(file.Source) {
		t.Fatal("overlay did not change the library")
	}
	sum := "std/drum-machines std sha256:" + oldDrumMachinesPin
	codes := pinCodes(t, "std/drum-machines", "drum-machines.boom-kit", sum, map[string][]byte{file.Path: []byte(changed)})
	if !hasCode(codes, "CICADA-LIB-HASH") {
		t.Fatalf("changed library loaded under the old pin: %v", codes)
	}
}

func TestOldDrumMachinesHashFailsElsewhere(t *testing.T) {
	cases := []struct{ name, imp, track, sum string }{
		{"other library", "std/drums", "drums.steel", "std/drums std sha256:" + oldDrumMachinesPin},
		{"user kind", "std/drum-machines", "drum-machines.boom-kit", "std/drum-machines user sha256:" + oldDrumMachinesPin},
		{"project kind", "std/drum-machines", "drum-machines.boom-kit", "std/drum-machines project sha256:" + oldDrumMachinesPin},
	}
	for _, c := range cases {
		if codes := pinCodes(t, c.imp, c.track, c.sum, nil); !hasCode(codes, "CICADA-LIB-HASH") {
			t.Errorf("%s: loaded under the old hash: %v", c.name, codes)
		}
	}
}
