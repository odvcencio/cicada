package project

import (
	"path/filepath"
	"strings"
	"testing"

)

// oldDrumMachinesPin is the std/drum-machines hash from before the kits were
// renamed; existing projects have it in their cicada.sum.
const oldDrumMachinesPin = "86c5317c6fca18853fc495e34acd8aabee6ae6ad91f7be3acf69829c3b3dad16"

func drumKitProject(t *testing.T, kit, sum string) string {
	t.Helper()
	t.Setenv("CICADA_LIBRARY", t.TempDir())
	root := t.TempDir()
	libraryWrite(t, root, "cicada.mod", "project kit-names\ncicada 2\nentry \"main.cicada\"\n")
	libraryWrite(t, root, "main.cicada", "cicada 2\nimport \"std/drum-machines\"\ntrack k drum-machines."+kit+" {}\npattern p drums steps=4 { bd: x... }\nscene main { k = p }\nsong { main }\n")
	if sum != "" {
		libraryWrite(t, root, "cicada.sum", "# cicada.sum: generated by cicada lib update\nstd/drum-machines std sha256:"+sum+"\n")
	}
	return root
}

func TestDrumKitNamesLoad(t *testing.T) {
	for _, kit := range []string{"boom-kit", "punch-kit", "eight-oh-eight", "nine-oh-nine"} {
		root := drumKitProject(t, kit, "")
		pinLibraryFixture(t, root)
		score, ds, err := LoadScore(filepath.Join(root, "main.cicada"), nil)
		if err != nil || score == nil || len(ds) != 0 {
			t.Fatalf("%s: %v %+v", kit, err, ds)
		}
	}
}

// A project pinned before the rename keeps loading, with the old kit names
// and with the new ones, until the owner re-pins.
func TestOldDrumMachinesPinStillLoads(t *testing.T) {
	for _, kit := range []string{"eight-oh-eight", "nine-oh-nine", "boom-kit", "punch-kit"} {
		root := drumKitProject(t, kit, oldDrumMachinesPin)
		score, ds, err := LoadScore(filepath.Join(root, "main.cicada"), nil)
		if err != nil || score == nil || len(ds) != 0 {
			t.Fatalf("old pin with %s: %v %+v", kit, err, ds)
		}
	}
}

func TestOtherDrumMachinesPinsStillFail(t *testing.T) {
	root := drumKitProject(t, "boom-kit", strings.Repeat("0", 64))
	d := requireLibraryDiagnostic(t, root, "CICADA-LIB-HASH")
	if d.Code != "CICADA-LIB-HASH" {
		t.Fatal(d)
	}
}

func TestDrumMachinesUpdateMovesOldPin(t *testing.T) {
	root := drumKitProject(t, "boom-kit", oldDrumMachinesPin)
	sources, err := ReadSources(filepath.Join(root, "main.cicada"), nil)
	if err != nil {
		t.Fatal(err)
	}
	data, changes, err := sources.UpdateLibraries("std/drum-machines")
	if err != nil || len(changes) != 1 || strings.Contains(string(data), oldDrumMachinesPin) {
		t.Fatalf("update: %v %v\n%s", changes, err, data)
	}
}
