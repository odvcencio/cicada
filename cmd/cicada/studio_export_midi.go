package main

import (
	"bytes"
	"crypto/rand"
	"encoding/json"
	"io"
	"mime"
	"net/http"
	"path/filepath"
	"strings"
	"sync"
	"time"

	"m31labs.dev/cicada/project"
	"m31labs.dev/cicada/smf"
)

type studioMIDIExportStatus struct {
	ID                    string   `json:"id"`
	Revision              string   `json:"revision"`
	SourceRevision        string   `json:"source_revision"`
	CurrentSourceRevision string   `json:"current_source_revision"`
	State                 string   `json:"state"`
	Notes                 int      `json:"notes"`
	PPQ                   uint16   `json:"ppq"`
	OmittedAudio          []string `json:"audio_tracks_omitted"`
}

// Keep the last completed MIDI independent of the WAV render. Generated bytes
// are immutable: a download can finish even when another export replaces them.
type studioMIDIExportController struct {
	mu       sync.Mutex
	active   bool
	status   studioMIDIExportStatus
	data     []byte
	filename string
}

func (s *studio) midiExportStatus(w http.ResponseWriter, _ *http.Request) {
	c := &s.midiExport
	c.mu.Lock()
	status := c.status
	status.State = "idle"
	if status.ID != "" {
		status.State = "ready"
	}
	if c.active {
		status.State = "preparing"
	}
	c.mu.Unlock()
	if status.ID != "" {
		status.CurrentSourceRevision, _ = project.ReadScoreRevision(s.path)
	}
	studioJSON(w, http.StatusOK, status)
}

func (s *studio) prepareMIDIExport(w http.ResponseWriter, r *http.Request) {
	if !studioSameOrigin(r) {
		studioJSON(w, http.StatusForbidden, map[string]string{"error": "cross-origin exports are not allowed"})
		return
	}
	if !strings.HasPrefix(r.Header.Get("Content-Type"), "application/json") {
		studioJSON(w, http.StatusUnsupportedMediaType, map[string]string{"error": "expected JSON"})
		return
	}
	var input struct {
		Revision       string `json:"revision"`
		SourceRevision string `json:"source_revision"`
	}
	decoder := json.NewDecoder(http.MaxBytesReader(w, r.Body, 4096))
	decoder.DisallowUnknownFields()
	err := decoder.Decode(&input)
	var extra any
	if err != nil || decoder.Decode(&extra) != io.EOF || input.SourceRevision == "" {
		studioJSON(w, http.StatusBadRequest, map[string]string{"error": "Refresh Studio to load the saved song before exporting notes."})
		return
	}
	inspection, err := inspectScore(s.path)
	if err != nil {
		studioJSON(w, http.StatusUnprocessableEntity, map[string]string{"error": err.Error()})
		return
	}
	if input.SourceRevision != inspection.sources.ScoreRevision() || input.Revision != "" && input.Revision != studioRevision(inspection.source) {
		studioJSON(w, http.StatusConflict, map[string]string{"error": "Saved score files or libraries changed. Refresh Studio before exporting notes again."})
		return
	}
	if hasDiagnosticErrors(inspection.diagnostics) {
		studioJSON(w, http.StatusUnprocessableEntity, map[string]string{"error": diagnosticError(inspection.diagnostics).Error()})
		return
	}
	c := &s.midiExport
	c.mu.Lock()
	if c.active {
		c.mu.Unlock()
		studioJSON(w, http.StatusConflict, map[string]string{"error": "MIDI is already being prepared. Wait for it to finish."})
		return
	}
	c.active = true
	c.mu.Unlock()
	defer func() {
		c.mu.Lock()
		c.active = false
		c.mu.Unlock()
	}()
	file, err := smf.FromProject(inspection.semantic, 0)
	var data bytes.Buffer
	if err == nil {
		err = smf.Encode(file, &data)
	}
	if err != nil {
		studioJSON(w, http.StatusUnprocessableEntity, map[string]string{"error": err.Error()})
		return
	}
	status := studioMIDIExportStatus{ID: rand.Text(), Revision: studioRevision(inspection.source), SourceRevision: input.SourceRevision, State: "ready", PPQ: file.PPQ}
	for _, track := range file.Tracks {
		status.Notes += len(track.Notes)
	}
	for _, track := range inspection.semantic.Tracks {
		if inspection.semantic.Edition == 2 && track.Kind == "audio" {
			status.OmittedAudio = append(status.OmittedAudio, track.ID)
		}
	}
	c.mu.Lock()
	c.status, c.data = status, data.Bytes()
	c.filename = strings.TrimSuffix(filepath.Base(s.path), filepath.Ext(s.path)) + "-notes.mid"
	c.mu.Unlock()
	studioJSON(w, http.StatusOK, status)
}

func (s *studio) midiExportFile(w http.ResponseWriter, r *http.Request) {
	c := &s.midiExport
	c.mu.Lock()
	id, data, name := c.status.ID, c.data, c.filename
	c.mu.Unlock()
	if id == "" || r.PathValue("id") != id {
		studioJSON(w, http.StatusConflict, map[string]string{"error": "this MIDI file is unavailable; prepare notes again"})
		return
	}
	w.Header().Set("Content-Type", "audio/midi")
	w.Header().Set("Cache-Control", "no-store")
	w.Header().Set("X-Content-Type-Options", "nosniff")
	w.Header().Set("Content-Disposition", mime.FormatMediaType("attachment", map[string]string{"filename": name}))
	http.ServeContent(w, r, name, time.Time{}, bytes.NewReader(data))
}
