// Package paramdefs loads the checked-in parameter catalog and generates
// language and kernel views from that data.
package paramdefs

import (
	"bytes"
	_ "embed"
	"encoding/json"
	"fmt"
	"go/format"
	"strings"
)

//go:embed registry.json
var registryData []byte

type Descriptor struct {
	Type        string   `json:"type,omitempty"`
	ID          string   `json:"id"`
	Path        string   `json:"path"`
	Scope       string   `json:"scope"`
	Voices      []string `json:"voices"`
	Source      string   `json:"source"`
	Unit        string   `json:"unit"`
	Min         float64  `json:"min"`
	Max         float64  `json:"max"`
	Default     float64  `json:"default"`
	Curve       string   `json:"curve"`
	Values      []string `json:"values,omitempty"`
	Off         bool     `json:"off,omitempty"`
	DisplayStep float64  `json:"display_step"`
	SmoothingMS float64  `json:"smoothing_ms"`
	Live        bool     `json:"live"`
	Automatable bool     `json:"automatable"`
	Persist     string   `json:"persist"`
	Schema      string   `json:"schema,omitempty"`
}

// Registry is loaded from the single checked-in data source in stable order;
// its order defines the ParamID ABI.
var Registry = loadRegistry()

func loadRegistry() []Descriptor {
	var rows []Descriptor
	if err := json.Unmarshal(registryData, &rows); err != nil {
		panic(fmt.Errorf("decode parameter registry data: %w", err))
	}
	return rows
}

func GoName(id string) string {
	name := strings.NewReplacer(".", "_", "-", "_").Replace(id)
	parts := strings.Split(name, "_")
	for i := range parts {
		if parts[i] != "" {
			parts[i] = strings.ToUpper(parts[i][:1]) + parts[i][1:]
		}
	}
	return strings.Join(parts, "")
}

func GenerateJSON() ([]byte, error) {
	return bytes.Clone(registryData), nil
}

func GenerateKernel() ([]byte, error) {
	var b bytes.Buffer
	fmt.Fprintln(&b, "// Code generated by cmd/paramgen; DO NOT EDIT.")
	fmt.Fprintln(&b, "package kernel")
	fmt.Fprintln(&b)
	fmt.Fprintln(&b, "type ParamID uint16")
	fmt.Fprintln(&b, "const (")
	for i, d := range Registry {
		fmt.Fprintf(&b, "\tParam%s ParamID = %d\n", GoName(d.ID), i)
	}
	fmt.Fprintf(&b, "\tParamCount = %d\n", len(Registry))
	fmt.Fprintln(&b, ")")
	fmt.Fprintln(&b, "// IsInteger reports whether a live parameter takes whole numbers only.")
	fmt.Fprintln(&b, "func IsInteger(id ParamID) bool {")
	fmt.Fprint(&b, "return false")
	for i := 0; i < len(Registry); i++ {
		if !Registry[i].Live || Registry[i].Type != "integer" {
			continue
		}
		j := i
		for j+1 < len(Registry) && Registry[j+1].Live && Registry[j+1].Type == "integer" {
			j++
		}
		fmt.Fprintf(&b, " || id >= Param%s && id <= Param%s", GoName(Registry[i].ID), GoName(Registry[j].ID))
		i = j
	}
	fmt.Fprintln(&b)
	fmt.Fprintln(&b, "}")
	fmt.Fprintln(&b, "func Param(id ParamID) (ParamSpec, bool) { if int(id) >= len(Params) { return ParamSpec{}, false }; return Params[id], true }")
	formatted, err := format.Source(b.Bytes())
	if err != nil {
		return nil, fmt.Errorf("format generated parameter table: %w", err)
	}
	return formatted, nil
}

func floatLiteral(value float64) string { return fmt.Sprintf("%g", value) }

// keysSplit returns the index of the first modeled-keyboard row. Those rows
// must form the tail of the registry, so the core kernel, which has no keyboard
// engine, can leave them out and treat their IDs as unknown.
func keysSplit() int {
	split := len(Registry)
	for i, d := range Registry {
		if strings.HasPrefix(d.ID, "keys.") {
			split = i
			break
		}
	}
	for _, d := range Registry[split:] {
		if !strings.HasPrefix(d.ID, "keys.") {
			panic("paramdefs: keyboard rows must be the last rows of the registry")
		}
	}
	return split
}

func writeRows(b *bytes.Buffer, from, to int) {
	for i := from; i < to; i++ {
		d := Registry[i]
		fmt.Fprintf(b, "\t{%d, %q, %q, %q, %q, %q, %q, %q, %s, %s, %s, %s, %s, %t, %t, %t},\n",
			i, d.ID, d.Path, d.Scope, d.Source, d.Unit, d.Curve, d.Persist,
			floatLiteral(d.Min), floatLiteral(d.Max), floatLiteral(d.Default), floatLiteral(d.DisplayStep), floatLiteral(d.SmoothingMS),
			d.Live, d.Automatable, d.Off)
	}
}

// GenerateKernelKeys writes the Params table that includes the keyboard rows.
// It builds everywhere except the core TinyGo kernel.
func GenerateKernelKeys() ([]byte, error) {
	var b bytes.Buffer
	fmt.Fprintln(&b, "// Code generated by cmd/paramgen; DO NOT EDIT.")
	fmt.Fprintln(&b, "//go:build !tinygo || keys")
	fmt.Fprintln(&b)
	fmt.Fprintln(&b, "package kernel")
	fmt.Fprintln(&b)
	fmt.Fprintln(&b, "type ParamSpec struct { ID ParamID; Name, Path, Scope, Source, Unit, Curve, Persist string; Min, Max, Default, DisplayStep float32; SmoothingMS float32; Live, Automatable, Off bool }")
	fmt.Fprintln(&b)
	fmt.Fprintln(&b, "// paramsBase holds every row before the modeled-keyboard controls.")
	fmt.Fprintln(&b, "var paramsBase = [...]ParamSpec{")
	writeRows(&b, 0, keysSplit())
	fmt.Fprintln(&b, "}")
	fmt.Fprintln(&b)
	fmt.Fprintln(&b, "func FindParam(name string) (ParamID, bool) { for i := range Params { if Params[i].Name == name { return ParamID(i), true } }; return 0, false }")
	fmt.Fprintln(&b)
	fmt.Fprintln(&b, "var paramsKeys = [...]ParamSpec{")
	writeRows(&b, keysSplit(), len(Registry))
	fmt.Fprintln(&b, "}")
	fmt.Fprintln(&b)
	fmt.Fprintln(&b, "// Params lists every registry row in ParamID order.")
	fmt.Fprintln(&b, "var Params = append(append(make([]ParamSpec, 0, ParamCount), paramsBase[:]...), paramsKeys[:]...)")
	return format.Source(b.Bytes())
}

// GenerateKernelCore writes the Params table of the core TinyGo kernel, which
// stops before the keyboard rows. Their IDs stay reserved but are unknown here.
func GenerateKernelCore() ([]byte, error) {
	var b bytes.Buffer
	fmt.Fprintln(&b, "// Code generated by cmd/paramgen; DO NOT EDIT.")
	fmt.Fprintln(&b, "//go:build tinygo && !keys")
	fmt.Fprintln(&b)
	fmt.Fprintln(&b, "package kernel")
	fmt.Fprintln(&b)
	fmt.Fprintln(&b, "// ParamSpec is the core kernel's view of a registry row. The names, paths,")
	fmt.Fprintln(&b, "// sources, units and persistence words are host metadata that the core")
	fmt.Fprintln(&b, "// never reads, so they are left out of the module.")
	fmt.Fprintln(&b, "type ParamSpec struct { ID ParamID; Scope, Curve string; Min, Max, Default, DisplayStep float32; SmoothingMS float32; Live, Automatable, Off bool }")
	fmt.Fprintln(&b)
	fmt.Fprintln(&b, "// Params lists the rows the core kernel knows. IDs from the first")
	fmt.Fprintln(&b, "// modeled-keyboard row up are rejected as unknown parameters.")
	fmt.Fprintln(&b, "var Params = [...]ParamSpec{")
	for i := 0; i < keysSplit(); i++ {
		d := Registry[i]
		fmt.Fprintf(&b, "\t{%d, %q, %q, %s, %s, %s, %s, %s, %t, %t, %t},\n", i, d.Scope, d.Curve,
			floatLiteral(d.Min), floatLiteral(d.Max), floatLiteral(d.Default), floatLiteral(d.DisplayStep), floatLiteral(d.SmoothingMS), d.Live, d.Automatable, d.Off)
	}
	fmt.Fprintln(&b, "}")
	return format.Source(b.Bytes())
}
