package paramdefs

import (
	"fmt"
	"strconv"
	"strings"
)

// GenerateRangesDoc writes the manual's parameter range reference from the same
// rows the compiler checks, so the page cannot drift from the diagnostics.
// cmd/paramgen writes it to docs/manual/parameter-ranges.md.
func GenerateRangesDoc() ([]byte, error) {
	var b strings.Builder
	b.WriteString("<!-- Generated by cmd/paramgen from internal/paramdefs; DO NOT EDIT. -->\n")
	b.WriteString("# Parameter ranges\n\n")
	b.WriteString("Every voice, drum, effect and master-chain setting has an allowed range. `cicada check`,\n")
	b.WriteString("`render`, Studio and the language server report each setting that is outside it, at\n")
	b.WriteString("the setting's own value. A message names the setting, the value as you wrote it, and\n")
	b.WriteString("the range:\n\n")
	b.WriteString("```text\n")
	b.WriteString("main.cicada:4:14: error CICADA-PARAM: drums oh_decay 50ms is below the minimum 150ms (range 150ms to 1.2s)\n")
	b.WriteString("```\n\n")
	b.WriteString("Scene settings and automation points that set the same parameters use the same\n")
	b.WriteString("wording. Each stage reports all of its errors in one run, but a stage runs only when the\n")
	b.WriteString("one before it is clean: scene settings are checked while the score is read, then track\n")
	b.WriteString("and effect declarations, then automation points. Fix the errors from one stage and run\n")
	b.WriteString("again to see the next. Limits are shown to six significant digits, rounded toward the inside of\n")
	b.WriteString("the range. Mixer settings (`level`, `pan`, sends) are described in the\n")
	b.WriteString("[edition 1 specification](../spec/edition-1.md#track-mixer-settings).\n")

	rows := append(append([]Descriptor(nil), Registry...), HostOnly...)
	type section struct {
		title string
		match func(Descriptor) bool
	}
	prefix := func(p string) func(Descriptor) bool {
		return func(d Descriptor) bool { return strings.HasPrefix(d.ID, p) }
	}
	sections := []section{
		{"Piano (`track name piano`)", prefix("piano.")},
	}
	for _, lane := range []struct{ id, name string }{
		{"bd", "bass drum"}, {"sd", "snare"}, {"ch", "closed hat"}, {"oh", "open hat"}, {"cp", "clap"}, {"rs", "rimshot"},
		{"lt", "low tom"}, {"mt", "mid tom"}, {"ht", "high tom"}, {"cb", "cowbell"}, {"cy", "cymbal"},
	} {
		id := lane.id
		sections = append(sections, section{"Drums, " + lane.name + " (`track name drums`)", func(d Descriptor) bool {
			return strings.HasPrefix(d.ID, "drum.") && strings.HasPrefix(d.Source, id+"_")
		}})
	}
	sections = append(sections,
		section{"Acid voice (`track name acid`)", prefix("acid.")},
		section{"Guitar voice (`track name guitar`, edition 2, experimental)", prefix("guitar.")},
	)
	for _, kind := range []struct{ id, name string }{
		{"drive", "Drive"}, {"delay", "Delay"}, {"reverb", "Reverb"}, {"comp", "Compressor"}, {"deesser", "De-esser"},
		{"eq", "EQ (track insert)"}, {"master.eq", "EQ on the master chain"}, {"transient", "Transient shaper (master)"}, {"width", "Width (master)"}, {"limiter", "Limiter (master)"},
	} {
		title := kind.name + " (`fx name " + kind.id + "`)"
		if kind.id == "master.eq" {
			title = kind.name + " (`fx name eq` listed in `master { insert }`; the frequency limit is 0.45 of 48 kHz, and the other settings use the track EQ limits)"
		}
		sections = append(sections, section{title, prefix("fx." + kind.id + ".")})
	}
	for _, s := range sections {
		var lines []string
		for _, d := range rows {
			if !s.match(d) || strings.HasPrefix(d.ID, "mix.") {
				continue
			}
			lines = append(lines, rangeDocRow(d))
		}
		if len(lines) == 0 {
			continue
		}
		fmt.Fprintf(&b, "\n## %s\n\n| Setting | Unit | Minimum | Maximum | Also accepts |\n| --- | --- | --- | --- | --- |\n", s.title)
		b.WriteString(strings.Join(lines, "\n"))
		b.WriteString("\n")
	}
	return []byte(b.String()), nil
}

func rangeDocRow(d Descriptor) string {
	unit := "unitless"
	switch strings.ToLower(d.Unit) {
	case "hz":
		unit = "Hz"
	case "ms":
		unit = "ms or s"
	case "db":
		unit = "dB"
	case "dbtp":
		unit = "dBTP"
	case "semitone":
		unit = "semitones"
	case "cent":
		unit = "cents"
	}
	var accepts []string
	for _, word := range d.Values {
		accepts = append(accepts, "`"+word+"`")
	}
	if d.Off {
		accepts = append(accepts, "`off`")
	}
	for _, v := range d.Isolated {
		accepts = append(accepts, "`"+strconv.FormatFloat(v, 'f', -1, 64)+"` ("+d.IsolatedNote+")")
	}
	low, high := FormatBound(d, d.Min, false), FormatBound(d, d.Max, true)
	if d.Curve == "enum" || d.Curve == "toggle" {
		low, high = "-", "-"
		unit = "word"
	}
	return fmt.Sprintf("| `%s` | %s | %s | %s | %s |", d.Source, unit, low, high, strings.Join(accepts, ", "))
}
